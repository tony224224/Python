# Ввод: 45 8 322
nums = list(map(int, input().split()))

# input().split() - разделяет строку на части по пробелам   "45 8 322" => ["45", "8", "322"]
# map(int, ["45", "8", "322"]) - применяет к каждому элементу списка функцию int    ["45", "8", "322"] => [45, 8, 322]
# list() - создаёт список из map

print(nums) # [45, 8, 322]